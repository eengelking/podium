#!/usr/bin/env node
// Builds the "Key functions" tables in docs/atlas/ATLAS.md from the source references in docs/atlas/podium-atlas.html,
// so the page and the document name the same functions and cannot drift apart.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

export const HTML = 'docs/atlas/podium-atlas.html';
export const DOC = 'docs/atlas/ATLAS.md';
export const START = '<!-- atlas-functions:start (generated by scripts/atlas-functions.mjs from docs/atlas/podium-atlas.html; edit the page, not this table) -->';
export const END = '<!-- atlas-functions:end -->';

// Parts in the order the tables list them, most important first (the same order as "The parts" in docs/atlas/ATLAS.md).
export const LOCATIONS = [
  ['Reporter', ['hooks', 'tx', 'cc', 'tools', 'helper', 'collect', 'rec', 'alt']],
  ['Network', ['p4317', 'p4318', 'proxy']],
  ['Server', ['ingest', 'fleet', 'sweeper', 'sse', 'routes', 'guards', 'admin', 'peers', 'ca', 'brokers', 'logs']],
  ['Storage', ['db', 'adb']],
  ['Console', ['ui_wall', 'ui_store', 'ui_detail', 'ui_respond', 'ui_admin', 'ui_traffic']],
];

// A reference counts as a key function when the page gives it as "name: what it does", with an optional leading "class ",
// and it is not an UPPER_CASE constant or a bare value.
const NAMED = /^(class )?([A-Za-z_]\w*)(\(\))?: (.+)$/;

/** The source references (file, line, text) the page keeps for each part, by part id. The list is read as text; nothing in the page is run. */
export function readRefs(html) {
  const consts = /const pM="([^"]*)",pS="([^"]*)",pSF="([^"]*)",pF="([^"]*)";/.exec(html);
  const start = html.indexOf('const REFS={');
  const end = html.indexOf('\n};', start);
  if (!consts || start < 0 || end < 0) throw new Error(`${HTML}: could not find the REFS list`);
  const prefix = { pM: consts[1], pS: consts[2], pSF: consts[3], pF: consts[4] };
  const refs = {};
  // One part to a line: ` id:[[path, line, "text"], ...],`, a path being a quoted string, or a prefix constant plus one.
  for (const line of html.slice(start, end).split('\n')) {
    const part = /^\s*(\w+):\[(.*)\],?\s*$/.exec(line);
    if (!part) continue;
    refs[part[1]] = [...part[2].matchAll(/\[(?:(p[A-Z]*)\+)?"([^"]+)",(\d+),("(?:[^"\\]|\\.)*")\]/g)].map((m) => [(prefix[m[1]] ?? '') + m[2], Number(m[3]), JSON.parse(m[4])]);
  }
  return refs;
}

/** The rows of the table: every named reference, in table order. */
export function readRows(html) {
  const refs = readRefs(html);
  const rows = [];
  for (const [location, ids] of LOCATIONS) {
    for (const id of ids) {
      // A part renamed or removed on the page must also change here, or its rows would drop out of the table without a word.
      if (!(id in refs)) throw new Error(`${HTML}: the part "${id}" is in the table order in scripts/atlas-functions.mjs but has no entry in REFS`);
      for (const [file, , text] of refs[id]) {
        const m = NAMED.exec(text);
        // A bare setting or limit ("BACKOFF_MS", "maxClients: 100") is not a function: it stays on the page only.
        if (m && !/^[A-Z][A-Z0-9_]+$/.test(m[2]) && !/^\d/.test(m[4])) rows.push({ location, id, file, kind: m[1] ?? '', name: m[2], call: m[3] ?? '', what: m[4] });
      }
    }
  }
  const known = new Set(LOCATIONS.flatMap(([, ids]) => ids));
  const stray = Object.keys(refs).filter((id) => !known.has(id));
  if (stray.length) throw new Error(`${HTML}: parts missing from the table order in ${path.basename(fileURLToPath(import.meta.url))}: ${stray.join(', ')}`);
  return rows;
}

/** A description as a table cell: capital first letter, no trailing full stop (one is added), pipes escaped. */
function describe(what) {
  let text = what;
  while (text.endsWith('.')) text = text.slice(0, -1);
  return `${text.charAt(0).toUpperCase()}${text.slice(1)}`.replaceAll('|', '\\|');
}

/** The generated Markdown between the markers. */
export function buildTables(rows) {
  const out = [];
  for (const [location] of LOCATIONS) {
    const mine = rows.filter((r) => r.location === location);
    if (!mine.length) continue;
    out.push(`### ${location}`, '', '| Location | Item | Description |', '|---|---|---|');
    for (const r of mine) out.push(`| ${r.location} | \`${r.kind}${r.name}${r.call}\` | ${describe(r.what)}. In \`${r.file}\`. |`);
    out.push('');
  }
  return out.join('\n').trimEnd();
}

/** docs/atlas/ATLAS.md with the generated tables brought up to date. */
export function render(root = REPO, html = fs.readFileSync(path.join(root, HTML), 'utf8')) {
  const doc = fs.readFileSync(path.join(root, DOC), 'utf8');
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${DOC}: the markers ${END} and its start line are missing`);
  return `${doc.slice(0, a + START.length)}\n\n${buildTables(readRows(html))}\n\n${doc.slice(b)}`;
}

/** Rows whose file is missing, or does not contain the name any more. */
export function findStale(rows, root = REPO) {
  const stale = [];
  for (const r of rows) {
    const file = path.join(root, r.file);
    if (!fs.existsSync(file)) stale.push(`${r.file}: no such file (${r.name})`);
    else if (!new RegExp(`\\b${r.name}\\b`).test(fs.readFileSync(file, 'utf8'))) stale.push(`${r.file}: ${r.name} is not in it any more`);
  }
  return stale;
}

export function main(argv, root = REPO) {
  if (argv.includes('-h') || argv.includes('--help')) {
    console.log(`Usage: node scripts/atlas-functions.mjs [--check]

Rewrites the "Key functions" tables in ${DOC} from the source references in ${HTML}.
The page is the source: add or change a reference there ("name: what it does", or "class Name: ..."), then run this.

  (no flag)  write ${DOC}
  --check    change nothing; exit 1 if ${DOC} is out of date, or if a named file or function is gone from the code
  -h         show this help`);
    return 0;
  }
  const html = fs.readFileSync(path.join(root, HTML), 'utf8');
  const rows = readRows(html);
  const next = render(root, html);
  if (argv.includes('--check')) {
    const problems = findStale(rows, root);
    if (next !== fs.readFileSync(path.join(root, DOC), 'utf8')) problems.unshift(`${DOC} is out of date: run node scripts/atlas-functions.mjs`);
    if (problems.length) {
      console.error(problems.join('\n'));
      return 1;
    }
    console.log(`ok: ${rows.length} key functions`);
    return 0;
  }
  fs.writeFileSync(path.join(root, DOC), next);
  console.log(`wrote ${rows.length} key functions to ${DOC}`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
